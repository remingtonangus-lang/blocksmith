#!/usr/bin/env python3
"""Lists questcheck's named runs (quest/src/headless/main.swift): every top-level `if` that picks a run by its flag
(`--X-only`, `--X`), with the one-line comment above it or on its line.

  quest/tools/listchecks.py              print "  --flag  comment" lines
  quest/tools/listchecks.py --swift OUT  write OUT: a Swift file with `questCheckList` for `questcheck --list-checks`
"""
import re, sys, os, json

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
MAIN = os.path.join(ROOT, "quest", "src", "headless", "main.swift")
FLAG = re.compile(r'(?:contains\(|firstIndex\(of: |arg\()"(--[a-z0-9][a-z0-9-]*)"')


def checks():
    lines = open(MAIN, encoding="utf-8").read().split("\n")
    out, seen = [], set()
    for i, line in enumerate(lines):
        if not line.startswith("if "):          # top-level picks only (nested `if`s read options of a run)
            continue
        m = FLAG.search(line)
        if not m:
            continue
        flag = m.group(1)
        if flag in seen or flag.startswith("--no-"):
            continue
        seen.add(flag)
        # The comment: the block of // lines right above (its first line), else the trailing // on the line itself.
        j, block = i - 1, []
        while j >= 0 and lines[j].lstrip().startswith("//"):
            block.insert(0, lines[j].strip()[2:].strip()); j -= 1
        note = ""
        if "//" in line:                         # a comment on the line itself
            note = line[line.rindex("//") + 2:].strip()
        for b in block:                          # else the block line that names this flag
            if not note and re.search(re.escape(flag) + r"(?![a-z0-9-])", b):
                note = b
        if not note and block and not block[0].startswith("--"):
            note = block[0]                      # else the block's first line, unless it names another flag
        if note.startswith(flag):
            note = note[len(flag):].lstrip(" :")
        out.append((flag, note))
    return out


if __name__ == "__main__":
    cs = checks()
    if len(sys.argv) > 2 and sys.argv[1] == "--swift":
        body = ",\n".join(f"    ({json.dumps(f)}, {json.dumps(n)})" for f, n in cs)
        new = ("// Generated by quest/tools/listchecks.py from quest/src/headless/main.swift: questcheck --list-checks.\n"
               f"let questCheckList: [(String, String)] = [\n{body}\n]\n")
        old = open(sys.argv[2]).read() if os.path.exists(sys.argv[2]) else None
        if new != old:                          # keep the date when nothing changed (incremental builds)
            open(sys.argv[2], "w").write(new)
    else:
        w = max(len(f) for f, _ in cs)
        for f, n in cs:
            print(f"  {f.ljust(w)}  {n}")
