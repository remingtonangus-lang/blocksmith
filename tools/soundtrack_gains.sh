#!/bin/bash
# P359 (e): measures every Sunderfall track (Resources/Music/sunderfall/*.m4a) with ffmpeg's EBU R128 meter and writes
# Sources/SoundtrackGains.swift: a gain per track that brings it to -16 LUFS (the composer's level, MusicLevelTests),
# held down so the sample peak stays under -1 dBFS. Rerun after adding or replacing a track.
set -e
cd "$(dirname "$0")/.."
OUT=Sources/SoundtrackGains.swift
{
  echo "// Generated by tools/soundtrack_gains.sh (P359 e): per-track gain to -16 LUFS, peaks kept under -1 dBFS."
  echo "enum SoundtrackGains {"
  echo "    static let table: [String: Float] = ["
  for f in Resources/Music/sunderfall/*.m4a; do
    n=$(basename "$f" .m4a)
    m=$(ffmpeg -nostats -i "$f" -af ebur128=peak=sample -f null - 2>&1 | tail -12)
    L=$(echo "$m" | awk '/I:/{print $2; exit}')
    P=$(echo "$m" | awk '/Peak:/{print $2; exit}')
    g=$(python3 -c "L=$L;P=$P;d=min(-16-L,-1-P);print('%.3f'%(10**(d/20)))")
    echo "        \"$n\": $g,      // $L LUFS, peak $P dBFS"
  done
  echo "    ]"
  echo "}"
} > "$OUT"
echo "wrote $OUT"
