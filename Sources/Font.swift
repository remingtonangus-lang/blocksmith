    static func texName(_ code: Int) -> String { "glyph_\(code)" }
    /// Rows a glyph draws (7, or 8 with a descender).
    static func rows(_ code: Int) -> Int { code > 32 && code < 127 ? glyphs[code - 32].count - 1 : 7 }
    static var names: [String] { (32..<127).map { texName($0) } }

    static func painters() -> [String: TextureGen.Painter] {
        var p: [String: TextureGen.Painter] = [:]
        for code in 32..<127 {
            let g = glyphs[code - 32]
            p[texName(code)] = { x, y in
                guard x < g[0] && y < g.count - 1 else { return TextureGen.clear }
                return (g[1 + y] >> x) & 1 == 1 ? V4(1, 1, 1, 1) : TextureGen.clear
            }
        }
        return p
    }

    static let layerBase: Int = Int(Tex.id(texName(32)))   // glyph layers are registered consecutively

    // Advance in font pixels (glyph width + 1 spacing).
    static func advance(_ code: Int) -> Int {
        if Glyphs.isGlyph(code) { return Glyphs.advance(code) }
        guard code >= 32 && code < 127 else { return 6 }
        return glyphs[code - 32][0] + 1
    }

    static func width(_ s: String) -> Int {
        var w = 0
        for u in s.unicodeScalars { w += advance(Int(u.value)) }
        return max(0, w - 1)
    }
